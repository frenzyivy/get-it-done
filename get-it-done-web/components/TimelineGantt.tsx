// Modal for adjusting a single tracked session — edit start/end, change a
// break label, attach a note, or delete the row. Phase 4 added the 30-minute
// "still-recent" safety rule that blocks start/end edits while letting label
// + note edits flow through.
function AdjustSessionModal({
  session,
  taskTitle,
  onClose,
  onStopLive,
  onSave,
  onDelete,
}: {
  session: TrackedSession | null;
  taskTitle: string;
  onClose: () => void;
  onStopLive: () => Promise<void>;
  onSave: (
    startedAtISO: string,
    endedAtISO: string,
    opts: { breakLabel: string | null; note: string | null },
  ) => Promise<void>;
  onDelete: () => Promise<void>;
}) {
  const isLive = !!session && !session.ended_at;
  const fallbackEnd = session
    ? new Date(
        new Date(session.started_at).getTime() +
          ((session.duration_seconds ?? 0) * 1000 || 60 * 60 * 1000),
      ).toISOString()
    : new Date().toISOString();
  const initialStart = session ? toLocalInputValue(session.started_at) : '';
  const initialEnd = session
    ? toLocalInputValue(session.ended_at ?? fallbackEnd)
    : '';
  const initialLabel = session?.break_label ?? 'lunch';
  const initialNote = session?.note ?? '';
  const [startVal, setStartVal] = useState(initialStart);
  const [endVal, setEndVal] = useState(initialEnd);
  // Phase 4 — break label + note are editable even when start/end aren't.
  const [breakLabel, setBreakLabel] = useState<string>(initialLabel);
  const [breakLabelOther, setBreakLabelOther] = useState<string>(
    BREAK_LABELS.some((b) => b.id === initialLabel) ? '' : initialLabel,
  );
  const [note, setNote] = useState<string>(initialNote);
  const [err, setErr] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);

  const isBreak = session?.block_type === 'break';
  const wasManuallyEntered = session?.manually_entered ?? false;

  // Phase 4 — 30-minute safety rule. A session ending less than 30 minutes
  // ago is "still settling" — the live timer may still be the source of
  // truth even after a stop. Block start/end edits on those rows; allow note
  // + label edits because they're metadata-only and useful.
  //
  // Sample "now" once at modal open via a lazy useState initializer (React 19
  // purity rule: no Date.now() during render). The 30-minute threshold is
  // coarse enough that a single snapshot for the modal's lifetime is fine.
  const [openedAtMs] = useState<number>(() => Date.now());
  const minutesSinceEnd =
    session && session.ended_at
      ? (openedAtMs - new Date(session.ended_at).getTime()) / 60_000
      : Number.POSITIVE_INFINITY;
  const recentSettle = minutesSinceEnd < 30;
  const timesLocked = isLive || recentSettle;

  if (!session) return null;

  const handleSave = async () => {
    setErr(null);
    const startISO = fromLocalInputValue(startVal);
    const endISO = fromLocalInputValue(endVal);
    if (!startISO || !endISO) {
      setErr('Please fill both times.');
      return;
    }
    if (new Date(endISO).getTime() <= new Date(startISO).getTime()) {
      setErr('End must be after start.');
      return;
    }
    const finalLabel = isBreak
      ? breakLabel === 'other'
        ? breakLabelOther.trim() || 'other'
        : breakLabel
      : null;
    setBusy(true);
    try {
      await onSave(startISO, endISO, {
        breakLabel: finalLabel,
        note: note.trim() || null,
      });
    } catch (e) {
      setErr((e as Error).message || 'Save failed.');
      setBusy(false);
    }
  };

  return (
    <div
      className="fixed inset-0 z-40 flex items-center justify-center bg-black/40"
      onClick={onClose}
    >
      <div
        className="bg-white rounded-[14px] p-5 w-[420px] max-w-[92vw] shadow-xl max-h-[92vh] overflow-y-auto"
        onClick={(e) => e.stopPropagation()}
      >
        <div className="flex items-center justify-between mb-1">
          <div className="text-[13px] font-extrabold uppercase tracking-[0.5px] text-[#1a1a2e]">
            Adjust {isBreak ? 'break' : 'session'}
          </div>
          {wasManuallyEntered && (
            <span
              className="text-[10px] font-bold uppercase tracking-[0.5px] px-[6px] py-[2px] rounded"
              style={{ background: '#fef3c7', color: '#92400e' }}
              title="This row was created or edited retroactively."
            >
              edited
            </span>
          )}
        </div>
        <div className="text-[12px] text-[#888] mb-3 truncate">{taskTitle}</div>

        {isLive && (
          <div className="mb-3 p-2 rounded-md bg-[#fef3c7] text-[11px] text-[#78350f]">
            This timer is still running. Stop it first, or just delete it.
          </div>
        )}
        {!isLive && recentSettle && (
          <div className="mb-3 p-2 rounded-md bg-[#fef3c7] text-[11px] text-[#78350f]">
            <b>Start / end locked.</b> This session is less than 30 minutes
            old — timer is the source of truth. You can still edit label and
            note. Try again once it settles.
          </div>
        )}
        {!isLive && (
          <div className="mb-3 p-2 rounded-md bg-[#fef3c7] text-[11px] text-[#78350f] flex items-start gap-2">
            <span aria-hidden>⚠</span>
            <span>
              Saving any edit flags this row as <b>manually entered</b> in
              Insights.
            </span>
          </div>
        )}

        <label className="block text-[11px] font-bold uppercase tracking-[0.5px] text-[#888] mb-1">
          Start
        </label>
        <input
          type="datetime-local"
          value={startVal}
          onChange={(e) => setStartVal(e.target.value)}
          disabled={timesLocked}
          className="w-full mb-3 px-2 py-2 border border-[#e5e7eb] rounded-md text-[13px] disabled:bg-[#f3f4f6]"
        />

        <label className="block text-[11px] font-bold uppercase tracking-[0.5px] text-[#888] mb-1">
          End
        </label>
        <input
          type="datetime-local"
          value={endVal}
          onChange={(e) => setEndVal(e.target.value)}
          disabled={timesLocked}
          className="w-full mb-3 px-2 py-2 border border-[#e5e7eb] rounded-md text-[13px] disabled:bg-[#f3f4f6]"
        />

        {isBreak && (
          <>
            <label className="block text-[11px] font-bold uppercase tracking-[0.5px] text-[#888] mb-1">
              Break label
            </label>
            <div className="grid grid-cols-3 gap-1 mb-2">
              {BREAK_LABELS.map((b) => {
                const on = breakLabel === b.id;
                return (
                  <button
                    key={b.id}
                    type="button"
                    onClick={() => setBreakLabel(b.id)}
                    className="px-2 py-[6px] rounded-md text-[12px] font-bold cursor-pointer transition-colors flex items-center justify-center gap-1"
                    style={{
                      background: on ? '#1a1a2e' : '#f3f4f6',
                      color: on ? '#fff' : '#666',
                    }}
                  >
                    <span aria-hidden>{b.icon}</span>
                    {b.label}
                  </button>
                );
              })}
            </div>
            {breakLabel === 'other' && (
              <input
                type="text"
                value={breakLabelOther}
                onChange={(e) => setBreakLabelOther(e.target.value)}
                placeholder="Custom label…"
                className="w-full mb-3 px-2 py-2 border border-[#e5e7eb] rounded-md text-[13px]"
              />
            )}
          </>
        )}

        <label className="block text-[11px] font-bold uppercase tracking-[0.5px] text-[#888] mb-1">
          Note <span className="font-normal lowercase text-[#bbb]">(optional)</span>
        </label>
        <textarea
          value={note}
          onChange={(e) => setNote(e.target.value)}
          rows={2}
          placeholder="Why edited? Anything to remember?"
          className="w-full mb-3 px-2 py-2 border border-[#e5e7eb] rounded-md text-[13px] resize-none"
        />

        {err && <div className="text-[11px] text-[#dc2626] mb-2">{err}</div>}

        <div className="flex gap-2 mt-4">
          <button
            onClick={onDelete}
            disabled={busy}
            className="px-3 py-2 text-[12px] font-bold rounded-md bg-[#fee2e2] text-[#991b1b] hover:bg-[#fecaca] disabled:opacity-50"
          >
            Delete
          </button>
          <div className="flex-1" />
          <button
            onClick={onClose}
            disabled={busy}
            className="px-3 py-2 text-[12px] rounded-md bg-[#f3f4f6] text-[#1a1a2e] hover:bg-[#e5e7eb] disabled:opacity-50"
          >
            Cancel
          </button>
          {isLive ? (
            <button
              onClick={onStopLive}
              disabled={busy}
              className="px-3 py-2 text-[12px] font-bold rounded-md bg-[#1a1a2e] text-white hover:opacity-90 disabled:opacity-50"
            >
              Stop now
            </button>
          ) : (
            <button
              onClick={handleSave}
              disabled={busy}
              className="px-3 py-2 text-[12px] font-bold rounded-md bg-[#1a1a2e] text-white hover:opacity-90 disabled:opacity-50"
            >
              Save
            </button>
          )}
        </div>
      </div>
    </div>
  );
}

// Phase 5 — quick-label modal for an auto-detected gap. Pre-fills the
// suggested label (italic "auto-detected" tag stays until the user confirms
// per the brief). Smaller than the full edit modal — gaps are quick to triage.
function LabelGapModal({
  gap,
  onClose,
  onConfirm,
}: {
  gap: BlockMeta;
  onClose: () => void;
  onConfirm: (label: string, note: string | null) => Promise<void>;
}) {
  // If the heuristic picked one of the 6 quick labels, default to it; else
  // default to "Lunch" so the user just picks something else if needed.
  const initialLabel = gap.suggestedLabel ?? 'lunch';
  const [label, setLabel] = useState<string>(initialLabel);
  const [labelOther, setLabelOther] = useState<string>('');
  const [note, setNote] = useState<string>('');
  const [busy, setBusy] = useState(false);
  const [err, setErr] = useState<string | null>(null);

  const handleConfirm = async () => {
    setErr(null);
    const final =
      label === 'other' ? labelOther.trim() || 'other' : label;
    setBusy(true);
    try {
      await onConfirm(final, note.trim() || null);
    } catch (e) {
      setErr((e as Error).message || 'Save failed.');
      setBusy(false);
    }
  };

  const startStr = new Date(gap.startMs).toLocaleTimeString('en-IN', {
    hour: '2-digit',
    minute: '2-digit',
  });
  const endStr = new Date(gap.endMs).toLocaleTimeString('en-IN', {
    hour: '2-digit',
    minute: '2-digit',
  });
  const durStr = fmtShort(Math.floor((gap.endMs - gap.startMs) / 1000));

  return (
    <div
      className="fixed inset-0 z-40 flex items-center justify-center bg-black/40"
      onClick={onClose}
    >
      <div
        className="bg-white rounded-[14px] p-5 w-[400px] max-w-[92vw] shadow-xl"
        onClick={(e) => e.stopPropagation()}
      >
        <div className="text-[13px] font-extrabold uppercase tracking-[0.5px] text-[#1a1a2e] mb-1">
          Label this gap
        </div>
        <div className="text-[12px] text-[#888] mb-1">
          {startStr} – {endStr} · {durStr}
        </div>
        {gap.suggestedLabel && (
          <div className="text-[11px] italic text-[#5b3fc8] mb-3">
            Auto-detected suggestion: {gap.suggestedLabel}
          </div>
        )}

        <label className="block text-[11px] font-bold uppercase tracking-[0.5px] text-[#888] mb-1">
          Label
        </label>
        <div className="grid grid-cols-3 gap-1 mb-2">
          {BREAK_LABELS.map((b) => {
            const on = label === b.id;
            return (
              <button
                key={b.id}
                type="button"
                onClick={() => setLabel(b.id)}
                className="px-2 py-[6px] rounded-md text-[12px] font-bold cursor-pointer transition-colors flex items-center justify-center gap-1"
                style={{
                  background: on ? '#1a1a2e' : '#f3f4f6',
                  color: on ? '#fff' : '#666',
                }}
              >
                <span aria-hidden>{b.icon}</span>
                {b.label}
              </button>
            );
          })}
        </div>
        {label === 'other' && (
          <input
            type="text"
            value={labelOther}
            onChange={(e) => setLabelOther(e.target.value)}
            placeholder="Custom label…"
            className="w-full mb-3 px-2 py-2 border border-[#e5e7eb] rounded-md text-[13px]"
          />
        )}

        <label className="block text-[11px] font-bold uppercase tracking-[0.5px] text-[#888] mb-1">
          Note <span className="font-normal lowercase text-[#bbb]">(optional)</span>
        </label>
        <textarea
          value={note}
          onChange={(e) => setNote(e.target.value)}
          rows={2}
          placeholder="What did you do during this gap?"
          className="w-full mb-3 px-2 py-2 border border-[#e5e7eb] rounded-md text-[13px] resize-none"
        />

        {err && <div className="text-[11px] text-[#dc2626] mb-2">{err}</div>}

        <div className="flex gap-2 mt-2">
          <div className="flex-1" />
          <button
            onClick={onClose}
            disabled={busy}
            className="px-3 py-2 text-[12px] rounded-md bg-[#f3f4f6] text-[#1a1a2e] hover:bg-[#e5e7eb] disabled:opacity-50"
          >
            Cancel
          </button>
          <button
            onClick={handleConfirm}
            disabled={busy}
            className="px-3 py-2 text-[12px] font-bold rounded-md bg-[#1a1a2e] text-white hover:opacity-90 disabled:opacity-50"
          >
            {busy ? 'Saving…' : 'Save break'}
          </button>
        </div>
      </div>
    </div>
  );
}

// <input type="datetime-local"> wants "YYYY-MM-DDTHH:mm" in local time.
// These two helpers round-trip between that and an ISO string.
function toLocalInputValue(iso: string): string {
  const d = new Date(iso);
  const pad = (n: number) => String(n).padStart(2, '0');
  return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}T${pad(d.getHours())}:${pad(d.getMinutes())}`;
}
function fromLocalInputValue(v: string): string | null {
  if (!v) return null;
  const d = new Date(v);
  if (Number.isNaN(d.getTime())) return null;
  return d.toISOString();
}
